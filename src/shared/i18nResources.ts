export function translateMain(
  lang: LanguageCode,
  keyPath: string,
  vars?: Record<string, string | number>
): string {
  const dict = i18nResources[lang]?.translation ?? i18nResources.en.translation
  const parts = keyPath.split('.')
  let cur: any = dict
  for (const p of parts) {
    cur = cur?.[p]
  }
  if (typeof cur !== 'string') return keyPath
  if (!vars) return cur
  return cur.replace(/\{\{(\w+)\}\}/g, (_, k) => String(vars[k] ?? ''))
}
